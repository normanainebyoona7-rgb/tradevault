// src/app/api/signals/route.ts

import { NextResponse } from "next/server";
import { getSession } from "@/lib/auth/session";
import { isAdminEmail } from "@/lib/admin";
import { dbConnect } from "@/lib/db/mongodb";
import Signal from "@/lib/models/signal";
import User from "@/lib/models/user";
import { sendTelegramSignal } from "@/lib/telegram";
import {
  createExecutableSignal,
  validateTradeLevels,
} from "@/lib/broker/signal-execution";

export async function GET() {
  try {
    const session = await getSession();
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    await dbConnect();
    const expiryTime = new Date(Date.now() - 24 * 60 * 60 * 1000);
    await Signal.updateMany(
      { isActive: true, createdAt: { $lt: expiryTime } },
      { isActive: false }
    );

    const user = await User.findById(session.id).lean();
    const userTier = (user as any)?.tier || "free";
    const allSignals = await Signal.find({ isActive: true })
      .sort({ createdAt: -1 })
      .lean();

    let signalsToReturn: any[] = [];
    if (userTier === "vvip") {
      signalsToReturn = allSignals;
    } else if (userTier === "vip") {
      signalsToReturn = allSignals.map((signal: any) => ({ ...signal, takeProfit3: "" }));
    } else {
      const autoSignals = allSignals.filter((signal: any) => signal.isAutoGenerated).slice(0, 5);
      signalsToReturn = autoSignals.map((signal: any) => ({
        ...signal,
        takeProfit2: "",
        takeProfit3: "",
      }));
    }

    return NextResponse.json({ signals: signalsToReturn, userTier, totalSignals: allSignals.length });
  } catch (error) {
    console.error("GET signals error:", error);
    return NextResponse.json({ error: "Failed to fetch signals" }, { status: 500 });
  }
}

export async function POST(request: Request) {
  try {
    const session = await getSession();
    if (!session || !isAdminEmail(session.email)) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await request.json().catch(() => null);
    if (!body || typeof body !== "object") {
      return NextResponse.json({ error: "Invalid JSON" }, { status: 400 });
    }

    if (body.direction === "neutral") {
      return NextResponse.json(
        {
          message: "Neutral signal — not saved and not sent to Telegram",
          skipped: true,
          reason: "AI has no clear direction for this setup",
        },
        { status: 200 }
      );
    }

    let levels;
    try {
      levels = validateTradeLevels(body);
    } catch (error: any) {
      return NextResponse.json(
        { error: "Validation failed", message: String(error?.message ?? error) },
        { status: 400 }
      );
    }

    await dbConnect();
    const isAutoGenerated = body.isAutoGenerated === true;
    const expiresAt = body.expiresAt ? new Date(body.expiresAt) : new Date(Date.now() + 24 * 60 * 60 * 1000);
    if (!Number.isFinite(expiresAt.getTime()) || expiresAt <= new Date()) {
      return NextResponse.json({ error: "expiresAt must be a valid future date" }, { status: 400 });
    }

    const metadata = {
      orderTypeDescription: String(body.orderTypeDescription ?? "").slice(0, 300),
      signalLabel: String(body.signalLabel ?? levels.direction.toUpperCase()).slice(0, 80),
      zone: body.zone ?? null,
      confidence: String(body.confidence ?? "").slice(0, 80),
      score: Number.isFinite(Number(body.score)) ? Number(body.score) : 0,
      session: String(body.session ?? "").slice(0, 80),
      source: String(body.source ?? "admin-manual").slice(0, 80),
      createdBy: String(session.email),
      notes: String(body.notes ?? "").slice(0, 1000),
      dedupeKey: body.dedupeKey ? String(body.dedupeKey).slice(0, 180) : undefined,
    };

    const result = isAutoGenerated
      ? await createExecutableSignal({
          levels,
          dedupeKey: metadata.dedupeKey,
          isAutoGenerated: true,
          source: metadata.source,
          createdBy: metadata.createdBy,
          expiresAt,
          metadata,
        })
      : { signal: await Signal.create({
          pair: levels.pair,
          direction: levels.direction,
          orderType: levels.orderType,
          entry: String(levels.entry),
          stopLoss: String(levels.stopLoss),
          takeProfit1: String(levels.takeProfit1),
          takeProfit2: levels.takeProfit2 ? String(levels.takeProfit2) : "",
          takeProfit3: levels.takeProfit3 ? String(levels.takeProfit3) : "",
          isActive: true,
          isAutoGenerated: false,
          expiresAt,
          ...metadata,
        }), duplicate: false };
    const signal = result.signal;

    if (!process.env.TELEGRAM_BOT_TOKEN || !process.env.TELEGRAM_CHANNEL_ID) {
      console.error("[Signal] Telegram skipped — missing TELEGRAM_BOT_TOKEN or TELEGRAM_CHANNEL_ID");
    } else {
      try {
        await sendTelegramSignal({
          pair: signal.pair,
          direction: signal.direction,
          signalLabel: signal.signalLabel || signal.direction.toUpperCase(),
          orderType: signal.orderType || "MARKET",
          orderTypeDescription: signal.orderTypeDescription || "",
          entry: signal.entry,
          stopLoss: signal.stopLoss,
          takeProfit1: signal.takeProfit1,
          takeProfit2: "",
          takeProfit3: "",
          isAutoGenerated,
          zone: signal.zone || null,
          confidence: signal.confidence || "NEUTRAL",
          score: signal.score || 0,
          session: signal.session || "",
        });
      } catch (telegramError) {
        console.error("Signal Telegram delivery failed:", telegramError);
      }
    }

    return NextResponse.json(
      { signal, executionId: "order" in result ? result.order?._id : undefined, duplicate: result.duplicate },
      { status: 201 }
    );
  } catch (error) {
    console.error("POST signal error:", error);
    return NextResponse.json({ error: "Failed to create signal" }, { status: 500 });
  }
}
