import { NextResponse } from "next/server";
import { dbConnect } from "@/lib/db/mongodb";
import { ADMIN_EMAIL } from "@/lib/admin";
import BrokerConnection from "@/lib/models/broker-connection";
import ExecutionLog from "@/lib/models/execution-log";
import Signal from "@/lib/models/signal";
import { decryptSecret } from "@/lib/broker/crypto";
import {
  isExecutorAuthorized,
  isExecutorConfigured,
} from "@/lib/broker/executor-auth";

const NO_STORE = { "Cache-Control": "no-store" };

export const dynamic = "force-dynamic";

export async function GET(request: Request) {
  if (!isExecutorConfigured()) {
    return NextResponse.json(
      { error: "EXECUTOR_SECRET is not configured on this server" },
      { status: 503, headers: NO_STORE }
    );
  }
  if (!isExecutorAuthorized(request)) {
    return NextResponse.json(
      { error: "Unauthorized" },
      { status: 401, headers: NO_STORE }
    );
  }

  try {
    await dbConnect();

    const conn = await BrokerConnection.findOne({ ownerEmail: ADMIN_EMAIL });
    if (!conn) {
      return NextResponse.json(
        {
          enabled: false,
          mode: "paper",
          signals: [],
          account: null,
          reason: "No broker connection configured",
        },
        { headers: NO_STORE }
      );
    }

    if (!conn.enabled) {
      return NextResponse.json(
        {
          enabled: false,
          mode: conn.mode,
          signals: [],
          account: null,
          reason: "Executor is disabled by the admin",
        },
        { headers: NO_STORE }
      );
    }

    const since = new Date(Date.now() - 24 * 60 * 60 * 1000);

    const executed = await ExecutionLog.find({
      createdAt: { $gt: since },
      status: { $in: ["placed", "paper"] },
    })
      .select("signalId")
      .lean();
    const executedIds = new Set(executed.map((e: any) => String(e.signalId)));

    const signals = await Signal.find({
      isActive: true,
      isAutoGenerated: true,
      direction: { $in: ["long", "short"] },
      createdAt: { $gt: since },
    })
      .sort({ createdAt: 1 })
      .limit(25)
      .lean();

    const pending = signals
      .filter((s: any) => !executedIds.has(String(s._id)))
      .map((s: any) => {
        const entry = Number(s.entry);
        const stopLoss = Number(s.stopLoss);
        const takeProfit1 = Number(s.takeProfit1);
        const takeProfit2 = Number(s.takeProfit2);
        const takeProfit3 = Number(s.takeProfit3);
        if (!Number.isFinite(entry) || !Number.isFinite(stopLoss)) return null;
        if (!Number.isFinite(takeProfit1) && !Number.isFinite(takeProfit3)) {
          return null;
        }
        return {
          id: String(s._id),
          pair: s.pair,
          direction: s.direction,
          orderType: s.orderType || "MARKET",
          entry,
          stopLoss,
          takeProfit1: Number.isFinite(takeProfit1) ? takeProfit1 : null,
          takeProfit2: Number.isFinite(takeProfit2) ? takeProfit2 : null,
          takeProfit3: Number.isFinite(takeProfit3) ? takeProfit3 : null,
          createdAt: s.createdAt,
        };
      })
      .filter(Boolean);

    // Credentials only leave the server for live mode over the
    // secret-authenticated executor channel.
    const account =
      conn.mode === "live"
        ? {
            login: conn.login,
            server: conn.server,
            password: decryptSecret(conn.passwordEnc),
          }
        : null;

    return NextResponse.json(
      {
        enabled: true,
        mode: conn.mode,
        riskPercent: conn.riskPercent,
        maxLot: conn.maxLot,
        maxDailyLossUsd: conn.maxDailyLossUsd,
        tpLevel: conn.tpLevel,
        symbolSuffix: conn.symbolSuffix,
        account,
        signals: pending,
      },
      { headers: NO_STORE }
    );
  } catch (error) {
    console.error("GET executor pending error:", error);
    return NextResponse.json(
      { error: "Failed to load pending signals" },
      { status: 500, headers: NO_STORE }
    );
  }
}
